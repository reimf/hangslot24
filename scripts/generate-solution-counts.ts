import { writeFileSync } from 'node:fs'
import { Combination } from '../src/combination.js'

const lines: string[] = []
for (const combination of Combination.generateAll())
  if (combination.solutionCount > 0)
    lines.push(`  [${combination.getNumbers().join(', ')}, ${combination.solutionCount}],`)

const source = `// Generated by scripts/generate-solution-counts.ts — do not edit by hand.
// Each entry is [a, b, c, d, solutionCount] for a solvable combination with a <= b <= c <= d.
export const SOLUTION_COUNTS: ReadonlyArray<readonly [number, number, number, number, number]> = [
${lines.join('\n')}
]
`

writeFileSync(new URL('../src/solution-counts.ts', import.meta.url), source)
console.log(`Wrote ${lines.length} solvable combinations`)
